import { writeFileSync, mkdirSync } from "node:fs";
import { z } from "zod";
import {
  ModelIR,
  Patch,
} from "../packages/semantic-ir/schema.js";
import {
  ToolSchemas,
  inputJSONSchema,
} from "../packages/semantic-ir/tool-registry.js";
import {
  OPERATORS,
  REGISTRY_HASH,
  operatorContract,
} from "../packages/compiler/index.js";
import { PIPELINE_POLICY } from "../hooks/server-registry/index.js";
import {
  OPERATOR_SEMANTICS,
  operatorDocs,
} from "../packages/compiler/operator-docs.js";
import {
  FailureResponse,
  ValidationReport,
  outputJSONSchema,
  portableTuples,
} from "../packages/semantic-ir/results.js";
mkdirSync("schemas", { recursive: true });
const schemas: Record<string, unknown> = {
  "model-ir-v1.schema.json": z.toJSONSchema(ModelIR),
  "parameter-patch-v1.schema.json": z.toJSONSchema(Patch),
  "tool-results-v1.schema.json": {
    type: "object",
    anyOf: Object.keys(ToolSchemas).map((name) => ({
      $ref: name + ".result.schema.json",
    })),
  },
  "tool-error-v1.schema.json": portableTuples(
    z.toJSONSchema(FailureResponse, { reused: "ref" }),
  ),
};
for (const [name, schema] of Object.entries(ToolSchemas)) {
  schemas[name + ".schema.json"] = inputJSONSchema(
    name as keyof typeof ToolSchemas,
  );
  schemas[name + ".result.schema.json"] = outputJSONSchema(
    name as keyof typeof ToolSchemas,
  );
}
schemas["operator-contract.schema.json"] = {
  type: "object",
  additionalProperties: false,
  required: [
    "version",
    "params",
    "refs",
    "output",
    "required_validators",
    "engine",
  ],
  properties: {
    version: { type: "integer" },
    params: {
      type: "object",
      additionalProperties: {
        type: "object",
        required: ["dimension"],
        properties: {
          dimension: { enum: ["length", "angle", "scalar"] },
          min: { type: "number" },
          max: { type: "number" },
          optional: { type: "boolean" },
          integer: { type: "boolean" },
        },
        additionalProperties: false,
      },
    },
    refs: {
      type: "array",
      items: { type: "integer" },
      minItems: 2,
      maxItems: 2,
    },
    output: { type: "string" },
    required_validators: { type: "array", items: { type: "string" } },
    engine: { type: "string" },
  },
};
schemas["validation-result.schema.json"] = z.toJSONSchema(ValidationReport, {
  reused: "ref",
});
for (const [filename, schema] of Object.entries(schemas))
  writeFileSync(
    "schemas/" + filename,
    JSON.stringify(
      {
        $schema: "https://json-schema.org/draft/2020-12/schema",
        ...(schema as object),
      },
      null,
      2,
    ) + "\n",
  );
writeFileSync(
  "schemas/operator-registry.json",
  JSON.stringify(
    {
      hash: REGISTRY_HASH,
      operators: Object.fromEntries(
        Object.entries(OPERATORS).map(([name, contract]) => [
          name,
          {
            ...contract,
            contract: operatorContract(name, contract as any),
            // Documentation only; not part of the registry hash.
            semantics: OPERATOR_SEMANTICS[name],
          },
        ]),
      ),
    },
    null,
    2,
  ) + "\n",
);
// Operator semantics for agents (llcad://operators, the modelling skill, cad_capabilities).
writeFileSync(
  "schemas/operator-docs.json",
  JSON.stringify(
    {
      $comment:
        "Generated by npm run schemas from packages/compiler/operator-docs.ts and the operator registry.",
      registry_hash: REGISTRY_HASH,
      ...operatorDocs(),
    },
    null,
    2,
  ) + "\n",
);
// The effective pipeline policy is generated from the registry, never hand-edited YAML.
writeFileSync(
  "hooks/server-registry/pipeline-policy.json",
  JSON.stringify(PIPELINE_POLICY, null, 2) + "\n",
);
console.log(
  `Generated ${Object.keys(schemas).length} schemas and operator registry.`,
);
